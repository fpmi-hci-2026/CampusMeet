"""Split long fixed-layout sheets at complete fragment boundaries for the viewer."""
import copy
import json
from pathlib import Path
from xml.etree import ElementTree as ET

from diagram_layout import Canvas, NS

ROOT = Path(__file__).resolve().parents[1]


def main():
    manifest = {}
    for path in sorted((ROOT/'docs/diagrams').rglob('*.svg')):
        if '.page-' in path.name:
            continue
        root = ET.parse(path).getroot()
        if root.get('data-layout') != 'fixed-lanes-v1' or float(root.get('height')) < 1600:
            continue
        info = json.loads(root.find('{' + NS + '}metadata').text)
        rows = [box for box in info['boxes'] if box[0] == 36]
        if len(rows) < 2:
            continue
        bands, current = [], []
        for box in rows:
            if current and box[3] - current[0][1] > 1150:
                bands.append(current)
                current = []
            current.append(box)
        if current:
            bands.append(current)
        if len(bands) == 1:
            continue
        for previous in path.parent.glob(path.stem + '.page-*.svg'):
            previous.unlink()
        pages = []
        for index, band in enumerate(bands, 1):
            first, last = band[0], band[-1]
            start, end = first[1]-28, last[3]+20
            title = root.find('{' + NS + '}title').text
            page = Canvas(title, f'Фрагмент {index} из {len(bands)} · текст показан в исходном масштабе')
            fragment = copy.deepcopy(root)
            for metadata in list(fragment.findall('{' + NS + '}metadata')):
                fragment.remove(metadata)
            fragment.set('x', '0')
            fragment.set('y', str(page.cursor))
            fragment.set('viewBox', f'0 {start} 1120 {end-start}')
            fragment.set('width', '1120')
            fragment.set('height', str(end-start))
            page.root.append(fragment)
            output = path.with_name(f'{path.stem}.page-{index:02d}.svg')
            page.save(output, page.cursor+end-start+16, {'page_of': path.name, 'page': index})
            pages.append({'file': output.name, 'label': f'Фрагмент {index} / {len(bands)}'})
        manifest[str(path.relative_to(ROOT/'docs/diagrams'))] = pages
    (ROOT/'docs/js/data/diagram-pages.js').write_text('/* Generated by scripts/paginate-diagrams.py */\nwindow.CampusMeetDiagramPages = '+json.dumps(manifest,ensure_ascii=False,indent=2)+';\n')
    print(f'Paginated {len(manifest)} diagrams into {sum(map(len, manifest.values()))} readable fragments')


if __name__ == '__main__':
    main()
