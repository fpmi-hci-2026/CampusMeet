"""Rebuild the existing offline report bundle from Markdown source reports."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
reports = {path.name: path.read_text() for path in sorted((root / 'docs/reports').glob('Lab*_report.md'))}
header = '/**\n * CampusMeet / EventHub — Embedded Academic Markdown Reports\n * Generated by scripts/sync-reports.py for offline file:/// browsing.\n */\n'
(root / 'docs/js/data/reports.js').write_text(header + 'window.CampusMeetReports = ' + json.dumps(reports, ensure_ascii=False) + ';\n')
print(f'Bundled {len(reports)} reports')
